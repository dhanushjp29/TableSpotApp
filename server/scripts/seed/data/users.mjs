export const seedUsers = async (ctx) => {
  for (let i = 0; i < USERS_SPEC.length; i += 1) {
    const spec = USERS_SPEC[i];
    const userCode = codeFor(CODE_PREFIX.USER, i + 1);
    const password = await bcrypt.hash(spec.password, SALT_ROUNDS);
    const { created, doc } = await upsertOne(
      User,
      { userCode },
      {
        userCode,
        fullName: spec.fullName,
        email: spec.email,
        password,
        phoneNumber: spec.phoneNumber,
        role: spec.role,
        favoriteCuisines: spec.favoriteCuisines,
        razorpayAccountStatus: spec.razorpayAccountStatus || "Not Connected",
        isEmailVerified: true,
        isActive: true,
        lastLoginAt: daysAgo(Math.max(1, (i % 12) + 1)),
      }
    );
    ctx.users.set(spec.key, { doc, created });
  }
  return { created: [...ctx.users.values()].filter((r) => r.created).length };
};

export default seedUsers;
