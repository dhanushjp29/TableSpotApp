export const seedRestaurants = async (ctx) => {
  for (let i = 0; i < RESTAURANTS_SPEC.length; i += 1) {
    const spec = RESTAURANTS_SPEC[i];
    const restaurantCode = codeFor(CODE_PREFIX.RESTAURANT, i + 1);
    const owner = ctx.users.get(spec.ownerKey).doc;

    const doc = {
      restaurantCode,
      slug: buildSlug(spec.restaurantName),
      ownerId: owner._id,
      restaurantName: spec.restaurantName,
      description: spec.description,
      contactPerson: spec.contactPerson,
      phoneNumber: spec.phoneNumber,
      email: spec.email,
      address: spec.address,
      city: spec.city,
      state: spec.state,
      country: spec.country,
      pincode: spec.pincode,
      location: spec.location,
      coverImage: coverFor(i),
      galleryImages: galleryFor(i + 2, 4),
      cuisineTypes: spec.cuisineTypes,
      operatingHours: spec.operatingHours,
      amenities: spec.amenities,
      services: spec.services,
      currentOffers: [],
      priceRange: spec.priceRange,
      averageCostForTwo: spec.averageCostForTwo,
      verificationStatus: spec.verificationStatus,
      verifiedBy: spec.verificationStatus === "Verified" ? ctx.users.get("admin").doc._id : null,
      verifiedAt: spec.verificationStatus === "Verified" ? new Date(Date.now() - 300 * 24 * 60 * 60 * 1000) : null,
      rejectionReason: spec.rejectionReason || "",
      razorpayAccountId: "",
      razorpayAccountStatus: "",
      gstin: spec.gstin || "",
      bookingPaymentPolicy: spec.bookingPaymentPolicy,
      cancellationPolicy: spec.cancellationPolicy,
      customerWaitingPeriod: spec.key === "street-wok" ? 20 : 30,
      isFeatured: Boolean(spec.isFeatured),
      isActive: true,
    };

    const { created, doc: saved } = await upsertOne(Restaurant, { restaurantCode }, doc);
    ctx.restaurants.set(spec.key, { doc: saved, created });
    ctx.ownerByRestaurant.set(spec.key, spec.ownerKey);
  }
  return { created: [...ctx.restaurants.values()].filter((r) => r.created).length };
};

export default seedRestaurants;
